# Variables 
# A variable is a name used to store a value in Python.

# Examples
age = 21
name = "Shadow"
salary = 35000

print(age)
print(name)
print(salary)

#        The basic syntax is:
 #     variable_name = value

name = "Shadow"       # string
age = 21              # integer
marks = 85.5          # float
is_student = True     # boolean

print(age)
print(type(age))
print(name)
print(type(name))
print(marks)
print(type(marks))
print(is_student)
print(type(is_student))


# Multiple variables

name = "Rahul"
age = 21
city = "Hyderabad"
# Like  these 
name, age, city = "Rahul", 21, "Hyderabad"

print(name)
print(age)
print(city)

# Assigning the same value

x = y = z = 100
print(x)
print(y)   # sse the output al values are same
print(z)

##
#  Important difference: = vs ==

age = 21 #  means assignment
